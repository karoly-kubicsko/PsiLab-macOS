#!/usr/bin/env python3
"""Transition states for ΨLab 7.0, stage 7.3: geomeTRIC's transition-state optimiser with PySCF.

geomeTRIC (an independent optimiser in translation-rotation-internal coordinates) searches for
first-order saddle points with transition=True; its Hessian is computed at the first step by
finite differences of the PySCF analytic gradients (hessian="first", the analogue of Gaussian's
CalcFC), tight thresholds. Starting geometries as in ΨLab's tests (built from ΨLab's parameters
with macqc/molecule.cpp's conventions):
  - H2O2, trans transition state of the internal rotation: dihedral H-O-O-H 160 degrees;
  - H2O2, cis transition state: dihedral 20 degrees;
  - NH3, inversion transition state (planar, D3h): H-N-H 119 degrees (at 116 degrees geomeTRIC,
    whose coordinates see no negative curvature there, descends to the pyramidal minimum);
RHF/aug-cc-pVDZ, at the transition states also the harmonic wavenumbers from PySCF's analytic
Hessian (AME 2020 masses, imaginary as negative numbers); NH3 also with CCSD(T)/aug-cc-pVDZ
(the CCSD(T) Lambda equations in the gradient, see pyscf_optimization_reference.py).

Usage (needs: pip install pyscf geometric):
  python3 reference/pyscf_ts_reference.py           # -> backend/tests/data/ts_reference.json
  python3 reference/pyscf_ts_reference.py --check   # recompute and compare
"""
import argparse
import json
import pathlib
import sys
import time

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pyscf_rhf_reference as rr  # noqa: E402
import pyscf_optimization_reference as orf  # noqa: E402
import pyscf_scan_reference as sr  # noqa: E402
import pyscf  # noqa: E402
from pyscf.geomopt.geometric_solver import optimize  # noqa: E402

OUT = rr.ROOT / "backend" / "tests" / "data" / "ts_reference.json"
B = rr.BOHR_IN_ANGSTROM

# (label, molecule, method, start parameters)
CASES = [
    ("H2O2 trans", "H2O2", "RHF", dict(dihedral=160.0)),
    ("H2O2 cis", "H2O2", "RHF", dict(dihedral=20.0)),
    ("NH3 planar", "NH3", "RHF", dict(angle=119.0)),
    ("NH3 planar", "NH3", "CCSD(T)", dict(angle=119.0)),
]
KEYS = ("ROO", "R1", "R2", "R3", "angle1", "angle2", "angle3", "dihedral")


def start(name, p):
    if name == "H2O2":
        g = dict(sr.H2O2)
        g.update(p)
        return sr.h2o2_atoms(g["ROO"], g["R"], g["angle"], g["dihedral"])
    g = dict(sr.NH3)
    g.update(p)
    return sr.nh3_atoms(g["R"], g["angle"])


def run(label, name, method, p):
    t0 = time.time()
    mol = sr.build(start(name, p), "aug-cc-pVDZ")
    solver = orf.solver(mol, method)
    if method == "RHF":
        # the displaced gradients of geomeTRIC's finite-difference Hessian need more than PySCF's
        # default 50 SCF iterations at these thresholds (1e-12 E_h, gradient 1e-9)
        solver.max_cycle = 300
    mol_ts = optimize(solver, maxsteps=200, transition=True, hessian="first", **orf.CONV)
    x = mol_ts.atom_coords(unit="Bohr")
    out = dict(label=label, molecule=name, basis="aug-cc-pVDZ", method=method, start=p,
               energy=float(orf.energy(mol_ts, method)), geometry=[[float(c) for c in row] for row in x])
    out.update(sr.parameters(name, x))
    if method == "RHF":
        out["frequencies"] = sr.frequencies(mol_ts)
    out["seconds"] = round(time.time() - t0, 1)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--tolerance", type=float, default=5e-5)
    args = ap.parse_args()
    stored = json.loads(OUT.read_text()) if OUT.exists() else None
    cases, worst = [], 0.0
    for label, name, method, p in CASES:
        r = run(label, name, method, p)
        cases.append(r)
        keys = [k for k in KEYS if k in r]
        line = (f"{label:11s} {method:8s} E = {r['energy']:.10f}  " + ", ".join(f"{k} {r[k]:.6f}" for k in keys) +
                ("  freq " + " ".join(f"{f:.2f}" for f in r["frequencies"]) if "frequencies" in r else "") +
                f"  ({r['seconds']} s)")
        if args.check and stored:
            ref = next(c for c in stored["cases"] if c["label"] == label and c["method"] == method)
            d = max(abs(abs(ref[k]) - abs(r[k])) for k in keys)
            worst = max(worst, d)
            line += f"  |diff| {d:.1e}"
        print(line, flush=True)
    if args.check:
        print(f"largest difference from the stored values: {worst:.1e}")
        return 0 if worst <= args.tolerance else 1
    doc = {"description": "Transition states from geomeTRIC (transition=True, Hessian by finite differences at the first "
                          "step) with PySCF analytic gradients: bond lengths in angstrom, angles in degrees, energies in "
                          "E_h, geometry in bohr; RHF wavenumbers (cm^-1, imaginary negative); generated by "
                          "reference/pyscf_ts_reference.py",
           "program": f"PySCF {pyscf.__version__}, geomeTRIC",
           "settings": "all electrons correlated; geomeTRIC thresholds " + json.dumps(orf.CONV),
           "bohr_in_angstrom": B, "cases": cases}
    OUT.write_text(json.dumps(doc, indent=1) + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
