def routine(name):
    """Logical lines of a subroutine body (after its header, up to END)."""
    body, on = [], False
    for no, t in L:
        tl = t.lower()
        if re.match(r'subroutine\s+' + name.lower() + r'\b', tl):
            on = True; continue
        if on:
            if tl in ('end', 'end subroutine'):
                break
            body.append(t)
    return body

def assigns(body, skip=()):
    """Plain assignment statements 'x=expr' converted to C++."""
    out = []
    for t in body:
        tl = t.lower().replace(' ', '')
        if tl.startswith(('implicit', 'dimension', 'data', 'return', 'save', 'common', 'parameter')):
            continue
        m = re.match(r'^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$', t)
        if not m:
            continue
        lhs = m.group(1).lower()
        if lhs in skip:
            continue
        out.append(f'    {lhs} = {conv(m.group(2))};')
    return out

def data_array(body, name, n):
    """Values of 'DATA name/.../' or 'data (name(i),i=a,b)/.../' statements (in order)."""
    vals = [None] * n
    for t in body:
        tl = t.lower()
        m = re.match(r'data\s+' + name + r'\s*/(.*)/\s*$', tl)
        if m:
            v = data_values(m.group(1)); vals[:len(v)] = v
            continue
        m = re.match(r'data\s*\(\s*' + name + r'\(i\)\s*,\s*i\s*=\s*(\d+)\s*,\s*(\d+)\s*\)\s*/(.*)/\s*$', tl)
        if m:
            a, b = int(m.group(1)), int(m.group(2)); v = data_values(m.group(3))
            assert len(v) == b - a + 1, (name, a, b, len(v))
            vals[a-1:b] = v
    assert all(x is not None for x in vals), name
    return vals

def data_idx(body, col, n):
    for t in body:
        tl = t.lower().replace(' ', '')
        m = re.match(r'data\(idx\(i,' + str(col) + r'\),i=1,' + str(n) + r'\)/(.*)/$', tl)
        if m:
            return [int(x) for x in data_values(m.group(1))]
    raise KeyError(col)

def cnum(v):
    v = v.strip()
    sign = ''
    if v[0] in '+-':
        sign, v = (v[0] if v[0] == '-' else ''), v[1:]
    return sign + num_cpp(v)

def arr(name, vals, ctype='double', per=4):
    lines = [f'const {ctype} {name}[{len(vals)}] = {{']
    for i in range(0, len(vals), per):
        lines.append('    ' + ', '.join(vals[i:i+per]) + ',')
    lines.append('};')
    return '\n'.join(lines)

