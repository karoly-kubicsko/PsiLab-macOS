#!/usr/bin/env python3
"""ΨLab 16.0: writes app/MacQC/BasisIdentity.swift from the basis-set files in basis/.

For every basis set of the menu and every element H-Ar, a group number that two basis sets share
exactly when the element has the same functions in both (the same shells, exponents and
contraction coefficients in the Gaussian94 file, and the same Cartesian or spherical d
functions). H and He are not in the (aug-)cc-pCVXZ files; the library uses (aug-)cc-pVXZ for them,
and so does this table. The app shows "same basis functions as ..." when a molecule's elements all
share the group of another basis set (e.g. LiH in def2-QZVP and def2-QZVPP).

Usage: python3 backend/tools/basis_identity.py  (from the repository root)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BASIS_DIR = os.path.join(ROOT, "basis")
OUT = os.path.join(ROOT, "app", "MacQC", "BasisIdentity.swift")

MENU = ["STO-1G", "STO-2G", "STO-3G",
        "6-31G", "6-31G*", "6-31+G", "6-31+G*", "6-31+G**", "6-31++G*", "6-31++G**",
        "6-311G", "6-311G*", "6-311+G", "6-311+G*", "6-311+G**", "6-311++G*", "6-311++G**",
        "6-311++G(2d,2p)", "6-311++G(3df,3pd)",
        "cc-pVDZ", "cc-pVTZ", "cc-pVQZ", "cc-pV5Z",
        "aug-cc-pVDZ", "aug-cc-pVTZ", "aug-cc-pVQZ", "aug-cc-pV5Z",
        "cc-pCVDZ", "cc-pCVTZ", "cc-pCVQZ", "cc-pCV5Z",
        "aug-cc-pCVDZ", "aug-cc-pCVTZ", "aug-cc-pCVQZ", "aug-cc-pCV5Z",
        "def2-SVP", "def2-mTZVP", "def2-mTZVPP", "def2-TZVP", "def2-TZVPP", "def2-TZVPPD",
        "def2-QZVP", "def2-QZVPP", "def2-QZVPPD"]
ELEMENTS = ["H", "He", "Li", "Be", "B", "C", "N", "O", "F", "Ne", "Na", "Mg", "Al", "Si", "P", "S", "Cl", "Ar"]


def file_name(basis):
    return (basis.lower().replace("+", "p").replace("*", "s").replace("(", "_").replace(")", "_")
            .replace(",", "_") + ".gbs")


def cartesian_d(basis):
    return basis.startswith("6-31G") or basis.startswith("6-31+") or basis.startswith("6-31++")


def blocks(path):
    """element -> canonical text of its block (shell lines with numbers normalised)."""
    out = {}
    lines = open(path).read().split("\n")
    i = 0
    while i < len(lines):
        t = lines[i].split()
        if len(t) == 2 and t[1] == "0" and t[0] in ELEMENTS:
            el, body = t[0], []
            i += 1
            while i < len(lines) and not lines[i].startswith("****"):
                u = lines[i].replace("D", "E").replace("d", "e").split() if not re.match(r"^\s*[SPDFGHI]+\s", lines[i]) \
                    else lines[i].split()
                if u:
                    try:
                        body.append(" ".join(u[:1] + [repr(float(x)) for x in u[1:]]) if re.fullmatch(r"[SPDFGHI]+", u[0])
                                    else " ".join(repr(float(x)) for x in u))
                    except ValueError:
                        body.append(" ".join(u))
                i += 1
            out[el] = "\n".join(body)
        i += 1
    return out


def main():
    data = {}
    for b in MENU:
        path = os.path.join(BASIS_DIR, file_name(b))
        if not os.path.exists(path):
            sys.exit("missing " + path)
        data[b] = blocks(path)
    # H and He in the core-valence sets: the valence sets' functions (as the library)
    for b in MENU:
        if "pCV" in b:
            v = b.replace("pCV", "pV")
            for el in ("H", "He"):
                if el not in data[b] and el in data[v]:
                    data[b][el] = data[v][el]
    groups = {el: [] for el in ELEMENTS}
    table = {}
    for b in MENU:
        row = {}
        for el in ELEMENTS:
            if el not in data[b]:
                continue
            key = (cartesian_d(b), data[b][el])
            if key not in groups[el]:
                groups[el].append(key)
            row[el] = groups[el].index(key)
        table[b] = row
    with open(OUT, "w") as f:
        f.write("//\n//  BasisIdentity.swift\n//  ΨLab 16.0 (generated by backend/tools/basis_identity.py from basis/*.gbs; do not edit)\n//\n\n")
        f.write("/// For each basis set of the menu and element H–Ar, a group number that two basis sets share\n")
        f.write("/// exactly when the element has the same functions in both (H and He in aug-cc-pCVXZ: the\n")
        f.write("/// aug-cc-pVXZ functions the library uses for them).\n")
        f.write("nonisolated enum BasisIdentity {\n")
        f.write("    static let groups: [String: [String: Int]] = [\n")
        for b in MENU:
            items = ", ".join('"%s": %d' % (el, table[b][el]) for el in ELEMENTS if el in table[b])
            f.write('        "%s": [%s],\n' % (b, items))
        f.write("    ]\n\n")
        f.write("    /// The other basis sets of the menu with the same functions as `basis` for every one of the\n")
        f.write("    /// elements (none if an element is beyond Ar or not in a set).\n")
        f.write("    static func sameFunctions(as basis: String, elements: [String]) -> [String] {\n")
        f.write("        guard let own = groups[basis], !elements.isEmpty else { return [] }\n")
        f.write("        return BasisSets.all.filter { other in\n")
        f.write("            other != basis && elements.allSatisfy { e in own[e] != nil && groups[other]?[e] == own[e] }\n")
        f.write("        }\n")
        f.write("    }\n")
        f.write("}\n")
    same = sum(1 for b in MENU for c in MENU if b < c and table[b] == table[c])
    print("wrote", OUT, "-", sum(len(g) for g in groups.values()), "distinct element blocks;", same, "pairs identical for all of H-Ar")


if __name__ == "__main__":
    main()
