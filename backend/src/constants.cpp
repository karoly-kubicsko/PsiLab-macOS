double isotope_mass(int Z) {
    if (Z < 1 || Z > kMaxZ) throw std::invalid_argument("isotope_mass: Z out of range");
    return kMass[Z - 1];
}

const char* isotope_label(int Z) {
    if (Z < 1 || Z > kMaxZ) throw std::invalid_argument("isotope_label: Z out of range");
    return kLabel[Z - 1];
}

