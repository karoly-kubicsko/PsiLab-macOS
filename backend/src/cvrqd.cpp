// Core correction (Partridge-Schwenke form): of the scaling factors f5z, fbasis, fcore, frest
// of the original, only fcore = -1 is non-zero, so the coefficients are -ccore and the two-body
// and mass terms vanish (as in the Fortran routine).
double cvps(double rij1, double rij2, double rij3) {
    struct Coefficients {
        double c[245];
        double reoh, b1, ce;
        Coefficients() {
            reoh = 0.958649 / 0.529177249;
            b1 = 2.0 * 0.529177249 * 0.529177249;
            const double rad = std::acos(-1.0) / 1.8e2;
            ce = std::cos(104.3475 * rad);
            for (int i = 0; i < 245; ++i) c[i] = (0.0 * 0.0 + 0.0 + (-1.0) * kCcore[i] + 0.0) * 4.556335e-6;
            c[0] = c[0] * 2.0;
        }
    };
    static const Coefficients k;
    const double x1 = (rij1 - k.reoh) / k.reoh;
    const double x2 = (rij2 - k.reoh) / k.reoh;
    const double x3 = std::cos(rij3) - k.ce;
    double fmat[16][3];
    fmat[1][0] = fmat[1][1] = fmat[1][2] = 1.0;
    for (int j = 2; j <= 15; ++j) {
        fmat[j][0] = fmat[j - 1][0] * x1;
        fmat[j][1] = fmat[j - 1][1] * x2;
        fmat[j][2] = fmat[j - 1][2] * x3;
    }
    double v = 0.0;
    for (int j = 2; j <= 245; ++j) {
        const double term = k.c[j - 1] * (fmat[kIdx1[j - 1]][0] * fmat[kIdx2[j - 1]][1] +
                                          fmat[kIdx2[j - 1]][0] * fmat[kIdx1[j - 1]][1]) *
                            fmat[kIdx3[j - 1]][2];
        v = v + term;
    }
    // mass correction: cmass * frest = 0, so v1 = v2 = 0; vhh = voh1 = voh2 = 0 (f5z = 0)
    v = v * std::exp(-k.b1 * ((rij1 - k.reoh) * (rij1 - k.reoh) + (rij2 - k.reoh) * (rij2 - k.reoh))) + k.c[0];
    return v;
}

