// x**n for an integer n (as gfortran: repeated squaring).
inline double ipow(double x, int n) {
    if (n < 0) return 1.0 / ipow(x, -n);
    double r = 1.0;
    while (n) {
        if (n & 1) r *= x;
        x *= x;
        n >>= 1;
    }
    return r;
}
